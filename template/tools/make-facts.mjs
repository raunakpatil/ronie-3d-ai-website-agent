// Turns the `knowledge` (and links, projects) in ronie.config.js into worker/src/facts.js — everything the AI knows about
// the owner. Run it after editing the config, then redeploy the worker:
//   node tools/make-facts.mjs && cd worker && npx wrangler deploy
import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const ctx = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(root, 'ronie.config.js'), 'utf8'), ctx);
const C = ctx.window.RONIE;
const K = C.knowledge || {};

const lines = [];
const add = (s) => lines.push(s);
add(`Name: ${C.owner}`);
if (K.status) add(`Current status (the newest information — wherever anything below disagrees, this is right): ${K.status}`);
if (K.summary) add(`Summary: ${K.summary}`);
if (C.assistant && C.assistant.email) add(`Email: ${C.assistant.email}`);
if (C.links && C.links.length) add(`Links: ${C.links.map((l) => `${l.label}: ${l.href.replace('mailto:', '')}`).join(' | ')}`);
for (const [title, items] of Object.entries(K.sections || {})) {
  add('');
  add(`${title}:`);
  for (const it of items) add(`- ${it}`);
}
if (C.projects && C.projects.length) {
  add('');
  add('Project links:');
  for (const p of C.projects) add(`- ${p.title}${p.link ? `: ${p.link}` : ''}`);
}
const facts = lines.join('\n');
fs.writeFileSync(path.join(root, 'worker/src/facts.js'), `// Generated by tools/make-facts.mjs from ronie.config.js — edit the config, not this file.\nexport const FACTS = ${JSON.stringify(facts)};\n`);
console.log(`worker/src/facts.js: ${lines.length} lines, ${facts.length} chars`);
